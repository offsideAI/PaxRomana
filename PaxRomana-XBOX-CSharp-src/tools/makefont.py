#!/usr/bin/env python3
"""Bakes the HUD fonts into Game/FontData.g.cs, so the game needs no font files or content pipeline at run time.

    pip install pillow
    python3 tools/makefont.py

Each font becomes one 8-bit alpha atlas plus glyph metrics. The three fonts are packed into a single blob, gzipped and
written as base64 string constants. Fonts: Cinzel and Barlow Condensed, both under the SIL Open Font License
(tools/fonts/*-OFL.txt).
"""
import base64, gzip, os, struct
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
CHARS = [chr(c) for c in range(32, 127)] + list("·×—…→←−°’é")
FONTS = [
    # name, file, pixel size, variable-font weight
    ("Ui", "BarlowCondensed-Medium.ttf", 46, None),
    ("UiBold", "BarlowCondensed-SemiBold.ttf", 46, None),
    ("Display", "Cinzel.ttf", 92, 800),
]
PAD = 4


def bake(name, file, size, weight):
    font = ImageFont.truetype(os.path.join(HERE, "fonts", file), size)
    if weight:
        font.set_variation_by_axes([weight])
    ascent, descent = font.getmetrics()
    missing = font.getmask("￿").getbbox()
    glyphs = []
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        img = None
        if w and h and ch != " ":
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
            if img.getbbox() is None:
                img = None
        glyphs.append({"ch": ch, "img": img, "w": w if img else 0, "h": h if img else 0, "xoff": x0, "yoff": y0, "adv": font.getlength(ch)})
    # shelf packing, tallest first
    width = 512 if size < 60 else 1024
    x = y = PAD
    row = 0
    for g in sorted(glyphs, key=lambda g: -g["h"]):
        if not g["img"]:
            g["x"] = g["y"] = 0
            continue
        if x + g["w"] + PAD > width:
            x = PAD; y += row + PAD; row = 0
        g["x"], g["y"] = x, y
        x += g["w"] + PAD
        row = max(row, g["h"])
    height = 1
    while height < y + row + PAD:
        height *= 2
    atlas = Image.new("L", (width, height), 0)
    for g in glyphs:
        if g["img"]:
            atlas.paste(g["img"], (g["x"], g["y"]))
    out = struct.pack("<B", len(name)) + name.encode("ascii")
    out += struct.pack("<HHHHHH", size, ascent, descent, width, height, len(glyphs))
    for g in glyphs:
        out += struct.pack("<HHHHHhhf", ord(g["ch"]), g["x"], g["y"], g["w"], g["h"], g["xoff"], g["yoff"], g["adv"])
    out += atlas.tobytes()
    print(f"{name}: {size}px, atlas {width}x{height}, {len(glyphs)} glyphs")
    return out


blob = struct.pack("<B", len(FONTS)) + b"".join(bake(*f) for f in FONTS)
text = base64.b64encode(gzip.compress(blob, 9, mtime=0)).decode("ascii")
lines = [text[i:i + 4000] for i in range(0, len(text), 4000)]
path = os.path.join(HERE, "..", "Game", "FontData.g.cs")
with open(path, "w", newline="\n") as f:
    f.write("// Generated by tools/makefont.py. Do not edit: run the script again instead.\n")
    f.write("// Glyph atlases for Cinzel and Barlow Condensed (SIL Open Font License, see tools/fonts).\n")
    f.write("namespace PaxRomana\n{\n    static class FontData\n    {\n        public static readonly string[] Chunks =\n        {\n")
    for line in lines:
        f.write(f'            "{line}",\n')
    f.write("        };\n    }\n}\n")
print(f"wrote {os.path.normpath(path)}: {len(blob)} bytes raw, {len(text)} base64 chars")
