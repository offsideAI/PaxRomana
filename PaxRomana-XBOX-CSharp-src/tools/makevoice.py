#!/usr/bin/env python3
"""Generates the voice-over for the Level Zero intro with ElevenLabs text-to-speech.

    ELEVENLABS_API_KEY=... python3 tools/makevoice.py

One clip per intro card is written to assets/voice/intro<N>.wav (16-bit mono PCM), and the clip lengths are written
to Game/IntroVoice.g.cs, which is what times the intro: each card stays up for as long as its clip runs. Run it
again only if the narration below or the voice changes, then build as usual.

The key is read from the environment and never written anywhere. Needs only the Python standard library.
"""
import json, os, struct, sys, urllib.error, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
API = "https://api.elevenlabs.io/v1"
VOICE_NAME = "Brian"
VOICE_ID = "nPczCjzI2devNBz1zQrb"       # Brian (ElevenLabs premade voice); looked up by name first, this is the fallback
MODEL = "eleven_multilingual_v2"
RATE = 24000                             # pcm_24000: raw 16-bit little-endian mono
SETTINGS = {"stability": 0.5, "similarity_boost": 0.8, "style": 0.15, "use_speaker_boost": True}
SEED = 1944

# What the narrator says over each intro card, in order. The cards themselves are in Game/Hud.cs (IntroScript).
LINES = [
    "Research and Analysis Wing. Field dossier. Level Zero: The Keys.",
    "Bavaria. Summer, nineteen forty-four. Beyond this valley, the Reich is enriching uranium two thirty-five. "
    "The works are walled, wired and watched. No one walks in.",
    "Burg Adlerstein. The keys to the enrichment zone lie in a strongbox, in the vault of the castle keep, "
    "behind a garrison of twenty-nine.",
    "Your orders, agent. Clear the castle, and take the keys. Level One: enter the zone, and break it from the inside.",
]


def call(path, key, body=None):
    req = urllib.request.Request(API + path, data=json.dumps(body).encode() if body is not None else None,
                                 headers={"xi-api-key": key, "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return r.read()
    except urllib.error.HTTPError as e:
        sys.exit(f"ElevenLabs returned HTTP {e.code} for {path}: {e.read()[:400].decode('utf-8', 'replace')}")


def voice_id(key):
    for v in json.loads(call("/voices", key)).get("voices", []):
        if v["name"].lower().startswith(VOICE_NAME.lower()):
            print(f"voice: {v['name']} ({v['voice_id']})")
            return v["voice_id"]
    print(f"voice {VOICE_NAME} not listed for this account; using {VOICE_ID}")
    return VOICE_ID


def tidy(pcm):
    """Trim the silence at both ends, bring the peak to about -1 dB, and fade the first and last few milliseconds."""
    s = list(struct.unpack(f"<{len(pcm) // 2}h", pcm[:len(pcm) // 2 * 2]))
    loud = [i for i, v in enumerate(s) if abs(v) > 500]
    if not loud:
        sys.exit("the clip came back silent")
    pad = int(RATE * 0.06)
    s = s[max(0, loud[0] - pad):min(len(s), loud[-1] + pad * 3)]
    gain = min(4.0, 29000 / max(abs(v) for v in s))
    fade = int(RATE * 0.012)
    out = []
    for i, v in enumerate(s):
        k = gain * min(1.0, i / fade, (len(s) - 1 - i) / fade)
        out.append(max(-32767, min(32767, int(v * k))))
    return struct.pack(f"<{len(out)}h", *out)


def wav(pcm):
    return (b"RIFF" + struct.pack("<I", 36 + len(pcm)) + b"WAVEfmt " + struct.pack("<IHHIIHH", 16, 1, 1, RATE, RATE * 2, 2, 16)
            + b"data" + struct.pack("<I", len(pcm)) + pcm)


def main():
    key = os.environ.get("ELEVENLABS_API_KEY")
    if not key:
        sys.exit("Set ELEVENLABS_API_KEY in the environment.")
    vid = voice_id(key)
    out_dir = os.path.join(HERE, "..", "assets", "voice")
    os.makedirs(out_dir, exist_ok=True)
    seconds = []
    for i, text in enumerate(LINES):
        body = {"text": text, "model_id": MODEL, "voice_settings": SETTINGS, "seed": SEED}
        if i > 0:
            body["previous_text"] = LINES[i - 1]
        if i + 1 < len(LINES):
            body["next_text"] = LINES[i + 1]
        pcm = tidy(call(f"/text-to-speech/{vid}?output_format=pcm_{RATE}", key, body))
        name = f"intro{i + 1}.wav"
        with open(os.path.join(out_dir, name), "wb") as f:
            f.write(wav(pcm))
        seconds.append(len(pcm) / 2 / RATE)
        print(f"{name}: {seconds[-1]:.2f} s, {len(text)} characters")
    path = os.path.join(HERE, "..", "Game", "IntroVoice.g.cs")
    with open(path, "w", newline="\n") as f:
        f.write("// Generated by tools/makevoice.py. Do not edit: run the script again instead.\n")
        f.write("// Lengths of the intro voice-over clips in assets/voice, which set how long each intro card stays up.\n")
        f.write("namespace PaxRomana\n{\n    public static class IntroVoice\n    {\n")
        f.write("        public const string Folder = \"assets/voice\";\n")
        f.write("        public static readonly string[] Files = { " + ", ".join(f'"intro{i + 1}.wav"' for i in range(len(LINES))) + " };\n")
        f.write("        public static readonly float[] Seconds = { " + ", ".join(f"{s:.2f}f" for s in seconds) + " };\n")
        f.write("    }\n}\n")
    print(f"wrote {os.path.normpath(path)}; {sum(len(t) for t in LINES)} characters used, {sum(seconds):.1f} s of speech")


if __name__ == "__main__":
    main()
